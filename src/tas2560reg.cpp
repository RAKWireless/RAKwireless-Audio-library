// ------------------------------------------------------------------
// registers_96khz — TAS2560 in "Mode 2 96k" (datasheet SLASE86E
// section 9.5.5.3). At 96 kHz the chip's Battery Guard, Thermal
// Foldback, Brownout, and Class-H tracking blocks are bypassed;
// the signal path is essentially ASI In → Volume → DAC. That means
// no DSP patch (pages 0x32 / 0x33 / 0x34) should be loaded — the
// stock upstream table's DSP patch is tuned for 48 kHz Mode 2 and
// would program 96 kHz operation with the wrong biquad coefficients.
//
// This table is the stock init sequence up through the pre-DSP-patch
// pause, but with:
//   - reg 0x04 changed from 0x4F (Class-H 15 dB) to 0x5F (Class-G
//     15 dB) — Class-H tracking isn't supported at 96 kHz per the
//     datasheet, so we run Class-G (always-max boost).
//   - DSP patch block omitted entirely.
//   - Final PWR_CTRL_1 = 0x40 (power up with boost, unmuted). Stock
//     ends 0x80 which is "up without boost"; at 96 kHz we want boost
//     on to match Class-G.
//
// apply_rate_dependent_init() still runs after this table and
// overwrites PCM_RATE (to 0x33 = 96 kHz) and PLL_J for the actual
// BCLK. That leaves this table safe to reuse across the two
// "96 kHz native" rates the driver targets (88.2 and 96 kHz).
// ------------------------------------------------------------------

