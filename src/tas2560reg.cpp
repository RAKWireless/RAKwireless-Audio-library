// ------------------------------------------------------------------
// Per-rate register table selector, used by TAS2560::begin(addr, rate):
//   8 kHz          -> registers_8khz[]  (PPC3 export)
//   88.2 / 96 kHz  -> registers_96khz[] (Mode 2 96k, no DSP patch)
//   anything else  -> registers[]       (upstream table)
// ------------------------------------------------------------------

const int registers_8khz_count =
    sizeof(registers_8khz) / sizeof(registers_8khz[0]);
const int registers_96khz_count =
    sizeof(registers_96khz) / sizeof(registers_96khz[0]);

const cfg_reg *tas2560_dsp_coeffs_for_rate(uint32_t fs, int *out_count)
{
  switch (fs) {
    case 8000:
      if (out_count) *out_count = registers_8khz_count;
      return registers_8khz;
    case 88200:
    case 96000:
      if (out_count) *out_count = registers_96khz_count;
      return registers_96khz;
    default:
      if (out_count) *out_count = sizeof(registers) / sizeof(registers[0]);
      return registers;
  }
}